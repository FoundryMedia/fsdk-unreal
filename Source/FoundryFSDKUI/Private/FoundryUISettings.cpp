void UFoundryUISettings::ApplyMatchmakingCopyOverrides()
{
	const UFoundryUISettings* Settings = Get();
	if (Settings == nullptr)
	{
		return;
	}
	for (const TPair<EFoundryWaitReason, FText>& Pair : Settings->MatchmakingWaitCopyOverrides)
	{
		FoundryMatchmakingCopy::SetWaitOverride(Pair.Key, Pair.Value);
	}
	for (const TPair<EFoundryFsdkResult, FText>& Pair : Settings->MatchmakingResultCopyOverrides)
	{
		FoundryMatchmakingCopy::SetResultOverride(Pair.Key, Pair.Value);
	}
}

void UFoundryUISettings::ApplyPartyDefaults()
{
	const UFoundryUISettings* Settings = Get();
	UFoundryPartyFollowComponent::SetFollowLeaderOnLeave(Settings == nullptr || Settings->bPartyFollowsLeaderOnLeave);
	// The core module cannot see IFoundryMenuHost, so the way a receiving member actually leaves is
	// installed from here: the same RequestLeaveMatch the kit's own leave buttons use.
	UFoundryPartyFollowComponent::SetLeaveExecutor([](APlayerController* Controller)
	{
		if (Controller == nullptr || !Controller->Implements<UFoundryMenuHost>())
		{
			return false;
		}
		IFoundryMenuHost::Execute_RequestLeaveMatch(Controller);
		return true;
	});
}

void UFoundryUISettings::PushGameSlug(UFoundrySocialSubsystem* Social)
{
	const UFoundryUISettings* Settings = Get();
	if (Social == nullptr || Settings == nullptr)
	{
		return;
	}
	if (!Settings->GameSlug.IsEmpty())
	{
		Social->SetGameSlug(Settings->GameSlug);
		return;
	}
	// No explicit slug: a queue key is "{gameSlug}/{modeSlug}", so the first queueable mode names the game.
	for (const FFoundryMatchmakingMode& Mode : Settings->MatchmakingModes)
	{
		if (!Mode.QueueName.IsEmpty())
		{
			Social->SetDefaultGameSlugFromQueue(Mode.QueueName);
			return;
		}
	}
}

TSubclassOf<UUserWidget> UFoundryUISettings::LoadWidgetClass(const TSoftClassPtr<UUserWidget>& Soft, const TCHAR* SettingName)
{
	if (Soft.IsNull())
	{
		UE_LOG(LogFoundryFSDKUI, Warning, TEXT("[UI] %s is not set - Project Settings -> Game -> Foundry UI"), SettingName);
		return nullptr;
	}

	UClass* Loaded = Soft.LoadSynchronous();
	if (Loaded == nullptr)
	{
		UE_LOG(LogFoundryFSDKUI, Error, TEXT("[UI] %s points at %s, which did not load"), SettingName, *Soft.ToString());
	}
	return Loaded;
}
