UFoundryUISettings::UFoundryUISettings()
{
	AccountUrl = TEXT("https://foundryplatform.app/account");

	// Generated by the FoundryUIBuild commandlet (FoundryFSDKUIEditor) into /FoundryFSDK/UI/Social.
	DefaultSocialDrawer = TSoftClassPtr<UUserWidget>(FSoftObjectPath(TEXT("/FoundryFSDK/UI/Social/WBP_FoundrySocialDrawer.WBP_FoundrySocialDrawer_C")));
	DefaultFriendRow = TSoftClassPtr<UUserWidget>(FSoftObjectPath(TEXT("/FoundryFSDK/UI/Social/WBP_FoundryFriendRow.WBP_FoundryFriendRow_C")));
	DefaultInviteRow = TSoftClassPtr<UUserWidget>(FSoftObjectPath(TEXT("/FoundryFSDK/UI/Social/WBP_FoundryInviteRow.WBP_FoundryInviteRow_C")));
	DefaultFriendMenu = TSoftClassPtr<UUserWidget>(FSoftObjectPath(TEXT("/FoundryFSDK/UI/Social/WBP_FoundryFriendMenu.WBP_FoundryFriendMenu_C")));
}

TSubclassOf<UUserWidget> UFoundryUISettings::LoadWidgetClass(const TSoftClassPtr<UUserWidget>& Soft, const TCHAR* SettingName)
{
	if (Soft.IsNull())
	{
		UE_LOG(LogFoundryFSDKUI, Warning, TEXT("[UI] %s is not set - Project Settings -> Game -> Foundry UI"), SettingName);
		return nullptr;
	}

	UClass* Loaded = Soft.LoadSynchronous();
	if (Loaded == nullptr)
	{
		UE_LOG(LogFoundryFSDKUI, Error, TEXT("[UI] %s points at %s, which did not load"), SettingName, *Soft.ToString());
	}
	return Loaded;
}
